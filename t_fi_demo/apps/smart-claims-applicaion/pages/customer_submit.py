"""Customer Mode — Submit Claim page."""
import streamlit as st
import uuid
from datetime import date
from utils.ml_inference import predict_damage, label_to_severity


_SEVERITY_COLOURS = {"minor": "#FF9800", "major": "#F44336", "unknown": "#9E9E9E"}


def _render_prediction_card(result):
    """Show the ML classification result prominently."""
    label = result["label"]
    score = result["score"]
    severity = label_to_severity(label)
    colour = _SEVERITY_COLOURS.get(label, "#9E9E9E")
    pct = f"{score * 100:.0f}"

    st.markdown(
        f"<div style='background:linear-gradient(135deg,{colour}22,{colour}11);"
        f"border-left:4px solid {colour};border-radius:12px;padding:20px;margin:12px 0'>"
        f"<p style='margin:0 0 6px;font-size:14px;color:#888'>AI Damage Assessment</p>"
        f"<p style='margin:0;font-size:28px;font-weight:700;color:{colour}'>"
        f"{severity}</p>"
        f"<p style='margin:4px 0 0;font-size:14px;color:#666'>"
        f"Confidence: <strong>{pct}%</strong></p></div>",
        unsafe_allow_html=True,
    )


def render():
    st.markdown("## Submit Your Claim")
    st.caption("Upload your accident image and provide claim details for instant analysis")

    # ---- image upload + instant classification ----
    st.markdown("### \U0001f4e4 Upload a car damage image")
    uploaded = st.file_uploader(
        "Drag and drop file here",
        type=["jpg", "jpeg", "png"],
        help="Limit 200 MB per file \u00b7 JPG, JPEG, PNG",
    )

    if uploaded:
        # Run ML only once per image (keyed by file name + size)
        image_key = f"{uploaded.name}_{uploaded.size}"
        if st.session_state.get("_ml_image_key") != image_key:
            with st.spinner("\U0001f52c Analyzing image\u2026"):
                result = predict_damage(uploaded.getvalue())
                st.session_state.ml_result = result
                st.session_state._ml_image_key = image_key

        # Show image and prediction side by side
        col_img, col_pred = st.columns([1, 1])
        with col_img:
            st.image(uploaded, caption="Uploaded image", use_column_width=True)
        with col_pred:
            _render_prediction_card(st.session_state.ml_result)
            st.info(
                "\U0001f4a1 This assessment is generated by our fine-tuned ResNet model. "
                "Fill in the form below and submit for a full rule-based evaluation.",
                icon="\u2139\ufe0f",
            )

    # ---- claim details form ----
    st.markdown("### Claim Details")
    st.caption("Please provide accurate information about your incident")

    with st.form("claim_form"):
        c1, c2 = st.columns(2)
        with c1:
            policy_number = st.text_input(
                "Policy Number", placeholder="Enter your policy number (optional for demo)"
            )
            claim_amount = st.number_input(
                "Claim Amount ($) *", min_value=0.0, step=100.0, format="%.2f"
            )
            self_severity = st.selectbox(
                "Self-Assessed Severity *",
                ["Minor Damage", "Total Loss"],
            )
            vehicles = st.selectbox(
                "Vehicles Involved *",
                ["1 Vehicle", "2 Vehicles", "3+ Vehicles"],
            )
        with c2:
            accident_location = st.text_input(
                "Accident Location *", placeholder="Enter location"
            )
            accident_date = st.date_input("Accident Date *", value=date.today())
            collision_type = st.selectbox(
                "Collision Type *",
                [
                    "Front-end", "Rear-end", "Side-impact", "Rollover",
                    "Multi-vehicle", "Single-vehicle", "Other",
                ],
            )

        additional_notes = st.text_area(
            "Additional Notes",
            placeholder="Provide any additional details about the incident\u2026",
        )

        submitted = st.form_submit_button(
            "\U0001f680 Submit Claim", type="primary", use_container_width=True
        )

    if submitted:
        if claim_amount <= 0:
            st.error("Please enter a valid claim amount.")
            return

        st.session_state.submitted_claim = {
            "claim_no": str(uuid.uuid4()),
            "policy_no": policy_number or "DEMO-" + uuid.uuid4().hex[:8].upper(),
            "accident_location": accident_location,
            "total": claim_amount,
            "claim_date": str(accident_date),
            "severity": self_severity,
            "collision_type": collision_type,
            "number_of_vehicles_involved": int(vehicles[0]),
            "additional_notes": additional_notes,
            "damage_prediction": st.session_state.get(
                "ml_result", {"label": "unknown", "score": 0}
            ),
        }
        st.session_state.show_results = True
        st.session_state.pop("ml_result", None)
        st.session_state.pop("_ml_image_key", None)
        st.rerun()
